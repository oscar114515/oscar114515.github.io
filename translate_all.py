def apply_translations(content, dictionary):
    """Apply all translations from dictionary to content, longest keys first."""
    # Sort by length descending to avoid partial matches
    sorted_keys = sorted(dictionary.keys(), key=len, reverse=True)
    for key in sorted_keys:
        content = content.replace(key, dictionary[key])
    return content

def process_language(src_dir, dst_dir, dictionary):
    """Process all HTML files from src_dir to dst_dir with translations."""
    os.makedirs(dst_dir, exist_ok=True)
    count = 0
    for fname in os.listdir(src_dir):
        if not fname.endswith('.html'):
            # Copy non-HTML files as-is
            src = os.path.join(src_dir, fname)
            dst = os.path.join(dst_dir, fname)
            if os.path.exists(src):
                with open(src, 'r', encoding='utf-8') as f:
                    content = f.read()
                with open(dst, 'w', encoding='utf-8') as f:
                    f.write(content)
            continue
        src = os.path.join(src_dir, fname)
        dst = os.path.join(dst_dir, fname)
        with open(src, 'r', encoding='utf-8') as f:
            content = f.read()
        content = apply_translations(content, dictionary)
        # Fix lang attribute
        content = content.replace('lang="zh-TW"', 'lang="' + dictionary.get('__lang__', 'en') + '"')
        # Fix privacy links to point to own language
        content = content.replace('/zh/privacy.html', '/' + os.path.basename(dst_dir) + '/privacy.html')
        with open(dst, 'w', encoding='utf-8') as f:
            f.write(content)
        count += 1
    print(f"  {dst_dir}: {count} HTML files processed")
    return count

